use std::{
	collections::{BTreeMap, HashMap},
	env, fs,
	path::{Path, PathBuf},
};

use miette::{IntoDiagnostic, Result, WrapErr, bail, miette};
use semver::{Version, VersionReq};
use serde::{Deserialize, Serialize};

use crate::{
	frontmatter::{self, Frontmatter},
	git,
};

pub(crate) const MANIFEST: &str = "skargo.toml";
pub(crate) const LOCK: &str = "skargo.lock";
const LOCK_HEADER: &str = "# @generated by skargo\n";
/// Where a `name = "<req>"` requirement finds its git; `SKARGO_REGISTRY` overrides.
const REGISTRY: &str = "https://github.com/EV-Main/skills";

type Releases = BTreeMap<String, BTreeMap<String, String>>;

enum Requirement {
	/// Git comes from the registry.
	Registry(VersionReq),
	Git(GitRequirement),
	Path(PathRequirement),
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct GitRequirement {
	git: String,
	version: VersionReq,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct PathRequirement {
	/// Relative to the manifest, or absolute.
	path: PathBuf,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(untagged)]
pub(crate) enum Locked {
	Release(Release),
	Path(Linked),
}

impl Locked {
	pub(crate) fn name(&self) -> &str {
		match self {
			Self::Release(r) => &r.name,
			Self::Path(l) => &l.name,
		}
	}
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct Release {
	pub(crate) name: String,
	pub(crate) git: String,
	/// Skill dir inside the repo at `commit`; derived, since the name is what identifies a skill.
	pub(crate) path: String,
	pub(crate) version: Version,
	pub(crate) commit: String,
}

/// A live link to a local checkout.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct Linked {
	pub(crate) name: String,
	/// Absolute: home-manager reads the lock from the store, where a relative path means nothing.
	pub(crate) path: PathBuf,
}

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Lock {
	skill: Vec<Locked>,
}

/// Which pins `sync` drops before resolving.
pub(crate) enum Refresh<'a> {
	None,
	All,
	Only(&'a [String]),
}

/// Brings `skargo.lock` in `dir` in line with `skargo.toml`, keeping every pin the manifest still allows and `refresh` spares.
pub(crate) fn sync(dir: &Path, refresh: Refresh) -> Result<Vec<Locked>> {
	let manifest_path = dir.join(MANIFEST);
	let manifest = parse_manifest(
		&fs::read_to_string(&manifest_path)
			.into_diagnostic()
			.wrap_err_with(|| format!("reading {}", manifest_path.display()))?,
		&manifest_path.display().to_string(),
	)?;

	let lock_path = dir.join(LOCK);
	let mut previous: HashMap<String, Locked> = match fs::read_to_string(&lock_path) {
		Ok(s) => toml::from_str::<Lock>(&s)
			.into_diagnostic()
			.wrap_err_with(|| format!("parsing {}", lock_path.display()))?
			.skill
			.into_iter()
			.map(|l| (l.name().to_owned(), l))
			.collect(),
		Err(e) if e.kind() == std::io::ErrorKind::NotFound => HashMap::new(),
		Err(e) => return Err(e).into_diagnostic().wrap_err_with(|| format!("reading {}", lock_path.display())),
	};
	match refresh {
		Refresh::None => {}
		Refresh::All => previous.clear(),
		Refresh::Only(names) =>
			for name in names {
				if !manifest.contains_key(name) {
					bail!("{name} is not in {}", manifest_path.display());
				}
				previous.remove(name);
			},
	}

	let registry = match env::var("SKARGO_REGISTRY") {
		Ok(r) => r,
		Err(env::VarError::NotPresent) => REGISTRY.to_owned(),
		Err(e) => return Err(e).into_diagnostic().wrap_err("reading $SKARGO_REGISTRY"),
	};
	let mut remotes: HashMap<String, Releases> = HashMap::new();
	let mut registry_manifest = None;
	let mut locked = Vec::new();
	for (name, req) in &manifest {
		let (git, version) = match req {
			Requirement::Path(p) => {
				locked.push(Locked::Path(link(name, &dir.join(&p.path))?));
				continue;
			}
			Requirement::Git(g) => (g.git.clone(), &g.version),
			Requirement::Registry(version) => match previous.get(name) {
				Some(Locked::Release(pin)) if version.matches(&pin.version) => (pin.git.clone(), version),
				_ => (registry_git(name, &registry, &mut remotes, &mut registry_manifest)?, version),
			},
		};
		if !remotes.contains_key(&git) {
			remotes.insert(git.clone(), git::remote_releases(&git)?);
		}
		let releases: Vec<(Version, &String)> = remotes[&git]
			.get(name)
			.into_iter()
			.flatten()
			.map(|(raw, commit)| {
				Version::parse(raw)
					.map(|v| (v, commit))
					.into_diagnostic()
					.wrap_err_with(|| format!("tag {name}{}{raw} in {git} is not semver", git::TAG_SEPARATOR))
			})
			.collect::<Result<_>>()?;

		if let Some(Locked::Release(pin)) = previous.remove(name)
			&& pin.git == git
			&& version.matches(&pin.version)
		{
			match releases.iter().find(|(v, _)| *v == pin.version) {
				Some((_, commit)) if **commit == pin.commit => locked.push(Locked::Release(pin)),
				Some((_, commit)) =>
					return Err(miette!(
						"tag {} in {git} moved from {} to {commit}; released tags are immutable",
						git::tag(name, &pin.version),
						pin.commit
					)),
				None => return Err(miette!("tag {} in {git} is gone; released tags are immutable", git::tag(name, &pin.version))),
			}
			continue;
		}

		let Some((version, commit)) = releases.iter().filter(|(v, _)| version.matches(v)).max_by(|a, b| a.0.cmp(&b.0)) else {
			let available: Vec<String> = releases.iter().map(|(v, _)| v.to_string()).collect();
			bail!("no release of {name} in {git} matches {version}; available: [{}]", available.join(", "));
		};
		locked.push(Locked::Release(resolve(name, &git, version, commit)?.0));
	}

	let rendered = format!("{LOCK_HEADER}{}", toml::to_string(&Lock { skill: locked.clone() }).into_diagnostic()?);
	fs::write(&lock_path, rendered).into_diagnostic().wrap_err_with(|| format!("writing {}", lock_path.display()))?;
	Ok(locked)
}

/// Dispatched by hand rather than `#[serde(untagged)]`, so a bad requirement says what is wrong with it.
fn parse_manifest(text: &str, origin: &str) -> Result<BTreeMap<String, Requirement>> {
	let raw: BTreeMap<String, toml::Value> = toml::from_str(text).into_diagnostic().wrap_err_with(|| format!("parsing {origin}"))?;
	raw.into_iter()
		.map(|(name, value)| {
			if let Some(v) = frontmatter::name_violation(&name) {
				bail!("{origin}: {v}");
			}
			let req = match value {
				toml::Value::String(req) => VersionReq::parse(&req).map(Requirement::Registry).into_diagnostic(),
				toml::Value::Table(t) if t.contains_key("path") => toml::Value::Table(t).try_into().map(Requirement::Path).into_diagnostic(),
				other => other.try_into().map(Requirement::Git).into_diagnostic(),
			}
			.wrap_err_with(|| format!("{origin}: requirement {name}"))?;
			Ok((name, req))
		})
		.collect()
}

/// The registry's own skills first, then the `git` its manifest gives the name.
fn registry_git(name: &str, registry: &str, remotes: &mut HashMap<String, Releases>, registry_manifest: &mut Option<BTreeMap<String, Requirement>>) -> Result<String> {
	if !remotes.contains_key(registry) {
		remotes.insert(registry.to_owned(), git::remote_releases(registry)?);
	}
	if remotes[registry].contains_key(name) {
		return Ok(registry.to_owned());
	}
	if registry_manifest.is_none() {
		let head = git::Fetched::try_new(registry, "HEAD")?;
		let text = if git::text(head.path(), &["ls-tree", "--name-only", &head.commit, MANIFEST])?.is_empty() {
			String::new()
		} else {
			git::text(head.path(), &["cat-file", "blob", &format!("{}:{MANIFEST}", head.commit)])?
		};
		*registry_manifest = Some(parse_manifest(&text, &format!("{registry} {MANIFEST}"))?);
	}
	let listed = registry_manifest.as_ref().expect("filled above");
	match listed.get(name) {
		Some(Requirement::Git(g)) => Ok(g.git.clone()),
		Some(_) => Err(miette!("{registry} {MANIFEST} lists {name} without a `git`")),
		None => {
			let mut known: Vec<&str> = remotes[registry].keys().chain(listed.keys()).map(String::as_str).collect();
			known.sort_unstable();
			bail!("{name} is not in the registry {registry}; it has: [{}]", known.join(", "));
		}
	}
}

fn link(name: &str, path: &Path) -> Result<Linked> {
	let path = fs::canonicalize(path).into_diagnostic().wrap_err_with(|| format!("{name}: path {}", path.display()))?;
	let skill_md = path.join("SKILL.md");
	let content = fs::read_to_string(&skill_md).into_diagnostic().wrap_err_with(|| format!("reading {}", skill_md.display()))?;
	let fm = frontmatter::parse(&content).map_err(|violations| miette!("{}: {}", skill_md.display(), violations.join("; ")))?;
	if fm.name != name {
		bail!("{} is named {:?}, {MANIFEST} calls it {name:?}", skill_md.display(), fm.name);
	}
	Ok(Linked { name: name.to_owned(), path })
}

/// Finds where the release keeps the skill and checks it is the release its tag claims.
pub(crate) fn resolve(name: &str, url: &str, version: &Version, commit: &str) -> Result<(Release, Frontmatter)> {
	let tag = git::tag(name, version);
	let fetched = git::Fetched::try_new(url, &format!("refs/tags/{tag}"))?;
	if fetched.commit != commit {
		bail!("{tag} in {url} moved to {} while resolving (was {commit}); released tags are immutable", fetched.commit);
	}

	let tree = git::text(fetched.path(), &["ls-tree", "-r", "-z", "--name-only", commit])?;
	let mut candidates = Vec::new();
	let mut matches = Vec::new();
	for file in tree.split('\0').filter(|f| *f == "SKILL.md" || f.ends_with("/SKILL.md")) {
		let content = git::text(fetched.path(), &["cat-file", "blob", &format!("{commit}:{file}")])?;
		match frontmatter::parse(&content) {
			Ok(fm) if fm.name == name => matches.push((file, fm)),
			Ok(fm) => candidates.push(format!("{file} (name {:?})", fm.name)),
			Err(violations) => candidates.push(format!("{file} (invalid: {})", violations.join("; "))),
		}
	}
	let (file, fm) = match matches.len() {
		1 => matches.pop().expect("len is 1"),
		0 => return Err(miette!("{tag} in {url} has no SKILL.md named {name:?}; candidates: [{}]", candidates.join(", "))),
		_ =>
			return Err(miette!(
				"{tag} in {url} has several SKILL.md named {name:?}: [{}]",
				matches.iter().map(|(f, _)| *f).collect::<Vec<_>>().join(", ")
			)),
	};
	if fm.version != *version {
		bail!("{tag} in {url}: {file} says metadata.version {}, the tag says {version}", fm.version);
	}
	let path = file.strip_suffix("SKILL.md").expect("filtered on this suffix").trim_end_matches('/');
	Ok((
		Release {
			name: name.to_owned(),
			git: url.to_owned(),
			path: path.to_owned(),
			version: version.clone(),
			commit: commit.to_owned(),
		},
		fm,
	))
}
